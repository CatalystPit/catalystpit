// EDGAR SIC INDUSTRY DESCRIPTIONS — the exact vocabulary, for refusing them as company names.
//
// An SIC description is what EDGAR prints for a filer's industry classification: "PHARMACEUTICAL
// PREPARATIONS", "METAL CANS", "RADIO BROADCASTING STATIONS". It is a closed, public SEC taxonomy,
// and it is NOT a company name — but screener_stocks.company held one for 2,805 symbols, and 92 of
// those phrases resolved to a real ticker through the company-name matcher. A headline reading
// "Meat Packing Plants Close Three Sites" would have been cashtagged $JBS.
//
// THIS IS AN EXACT SET, NOT A PATTERN. A regex that guesses at "industry-shaped" text either misses
// most of them (the previous one caught 757 of 2,805) or starts refusing real companies. Equality
// against the known vocabulary cannot do either. Verified against every SEC name we hold — 5,542
// Form 4 issuer names and 1,010 8-K registrant names — there are ZERO collisions: no real company
// is byte-identical to an SIC description.
//
// Server-side only in practice: the sole consumer is company-symbols.mjs, which is imported by
// primary-events.js and never by a client component. The content is public SEC taxonomy regardless
// and says nothing about our sources, feeds or vendors.
