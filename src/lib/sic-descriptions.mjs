// Compared on a normalised form so case, punctuation and spacing cannot defeat the match, and on the
// WHOLE name — "Aircraft Parts Manufacturing Inc" is a company, "AIRCRAFT PARTS" is a classification.
const norm = (s) => String(s || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
const SET = new Set(SIC_DESCRIPTIONS.map(norm));

/** True when `name` IS an EDGAR industry description rather than a company name. */
export const isSicDescription = (name) => {
  const k = norm(name);
  return k.length > 0 && SET.has(k);
};
