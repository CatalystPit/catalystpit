// Catalyst Pit X auto-poster — PURE logic. No DB, no network, no credentials.
//
// Everything that decides WHETHER to post and WHAT the post says lives here, so all of it is unit
// testable without touching X or the database. src/lib/x-publisher.js owns persistence and the API.
//
// The governing rule of this file is that it never invents anything. The post text is assembled
// from a canonical event's own Catalyst Pit wording and its own resolved ticker, and nothing else.
// No implications, no context, no prices we did not measure, no "investors are watching closely".

import { publicationVerdict } from './x-quality.mjs';
import { isTaxonomyLabel } from './news-normalize.mjs';
import { storyVerdict, factsOf } from './x-story.mjs';

export const MODES = ['off', 'dry_run', 'live'];

// Fail closed, and STRICTLY. An exact match against the three declared values — no trimming, no
// case folding, no aliases. Anything else, including "LIVE", "live " and "dry-run", is OFF.
//
// Forgiving parsing is the wrong instinct for a switch that starts publishing to a public account:
// a stray space should mean "not live", never "close enough to live".
export function resolveMode(raw) {
  return MODES.includes(raw) ? raw : 'off';
}

// The single gate on contacting X. Kept here, pure and exhaustively tested, so the proof that dry
// run cannot publish does not depend on being able to import the database layer.
export const canPublish = (rawMode) => resolveMode(rawMode) === 'live';

// ── eligibility ──────────────────────────────────────────────────────────────
// A canonical event qualifies when EITHER
//   A. it scored CRITICAL, or
//   B. any record in its cluster came from Walter Bloomberg, whatever the score.
//
// and in both cases the headline must already be CATALYST PIT'S OWN WORDING. That is the gate that
// makes "never post Walter Bloomberg's original wording" structural rather than a promise:
//   original  - rewritten by the model
//   composed  - written deterministically from an extracted assertion
//   rewrite_pending - still the source's sentence. NEVER eligible; it waits.
//   not_required    - the source's wording is final by design (SEC filings, exchange halt notices).
//                     Also never eligible: it is not ours to publish as our own.
const CATALYST_WORDING = new Set(['original', 'composed']);

export const WALTER_SOURCE = 'WALTERBLOOMBERG';
export const CRITICAL = 3;
export const HIGH = 2;

/**
 * @param {object} ev canonical event: { importance, headline_status, source_kind, sources[] }
 *   `sources` is every source code in the cluster, the canonical row's own included.
 * @returns {{eligible: boolean, reason: string|null, blocked: string|null}}
 */
export function evaluate(ev) {
  const sources = (ev?.sources || []).map((s) => String(s || '').toUpperCase());
  const isCritical = Number(ev?.importance) === CRITICAL;
  const hasWalter = sources.includes(WALTER_SOURCE);

  // HIGH or CRITICAL is the bar. The account exists to carry what Pit Wire already judged to matter,
  // and a second, stricter opinion about that was keeping real events off it. Walter provenance
  // still qualifies on its own, which is now mostly redundant given his HIGH floor, but it keeps
  // working if that floor ever changes.
  const isHigh = Number(ev?.importance) >= HIGH;
  if (!isHigh && !hasWalter) return { eligible: false, reason: null, blocked: 'below HIGH, no Walter provenance' };
  // SEC is never auto-posted. Its wording is the filing's, and its handling is out of scope here.
  if (ev?.source_kind === 'sec') return { eligible: false, reason: null, blocked: 'SEC' };
  // `not_required` is not a wait — it is a permanent state, so treating it as one made every event
  // carrying it PERMANENTLY ineligible. Measured over 72h that was 46 events, all of them exchange
  // halt lines, which are exactly the kind of thing a trading account should carry.
  //
  // The reason the wording gate exists at all is that a PUBLISHER's prose must never go out as
  // Catalyst Pit's own words. An exchange halt line is not prose: it is a mechanical statement of a
  // market fact ("RFAI halted, volatility pause"), generated by the engine from the exchange feed's
  // own fields. There is no author to misrepresent, so the wording gate has nothing to protect and
  // these go straight to the editorial gate, which decides whether THIS halt is worth posting.
  const mechanical = String(ev?.source_type || '') === 'halt'
    && String(ev?.headline_status || '') === 'not_required';
  if (!mechanical && !CATALYST_WORDING.has(String(ev?.headline_status || ''))) {
    // Not a rejection — a WAIT. The rewrite queue will reach it and the next pass reconsiders.
    return { eligible: false, reason: null, blocked: `awaiting Catalyst wording (${ev?.headline_status})` };
  }
  if (mechanical) return { eligible: true, reason: 'exchange halt', blocked: null };
  const reason = isCritical && hasWalter ? 'critical+walter' : isCritical ? 'critical' : isHigh ? 'high' : 'walter';
  return { eligible: true, reason, blocked: null };
}

// ── text hygiene ─────────────────────────────────────────────────────────────
// Characters the operator has ruled out, plus everything that makes an automated post look
// automated. Applied to the event's own words; it only ever REMOVES, never adds.
const EM_DASH = /[—―]/g;          // — ―
const FORBIDDEN = /[~|—―]/;        // asserted absent after sanitising
const EMOJI = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}\u{1F1E6}-\u{1F1FF}]/gu;
const HASHTAG = /(^|\s)#[A-Za-z0-9_]+/g;
const URL = /\bhttps?:\/\/\S+|\bwww\.\S+/gi;

export function sanitize(text) {
  return String(text || '')
    .replace(URL, ' ')
    .replace(EMOJI, ' ')
    .replace(HASHTAG, '$1')
    .replace(EM_DASH, ', ')                 // an em dash becomes ordinary punctuation, not a gap
    .replace(/[~|]/g, ' ')
    .replace(/\s*,\s*,\s*/g, ', ')
    .replace(/\s+/g, ' ')
    .replace(/\s+([,.;:!?])/g, '$1')
    .replace(/^[\s,;:.\-]+/, '')
    .trim();
}

// X's limit is 280. Stopping short leaves room for a reaction line and for any future suffix without
// re-testing the whole formatter.
export const MAX_POST = 270;

// Cut on a word boundary and never leave dangling punctuation. An ellipsis is added only when
// something was actually removed, so the reader can tell.
function clamp(text, budget) {
  if (text.length <= budget) return text;
  const cut = text.slice(0, budget - 1);
  const at = cut.lastIndexOf(' ');
  return `${(at > budget * 0.6 ? cut.slice(0, at) : cut).replace(/[\s,;:.\-]+$/, '')}…`;
}

// ── market reaction ──────────────────────────────────────────────────────────
// A second line is allowed ONLY from a measurement we actually hold, and only when it is fresh
// enough to be a reaction to this event rather than a stale daily figure. Nothing is computed or
// estimated here. If no reading qualifies the post goes out as one line, immediately — the reaction
// is never worth waiting for.
export const REACTION_MAX_AGE_MS = 30 * 60 * 1000;

export function reactionLine(reading, now = Date.now()) {
  if (!reading) return null;
  const { label, changePct, asOf } = reading;
  if (!label || !Number.isFinite(Number(changePct))) return null;
  const age = now - Number(asOf ?? NaN);
  if (!Number.isFinite(age) || age < 0 || age > REACTION_MAX_AGE_MS) return null;   // stale = omitted
  const pct = Number(changePct);
  if (Math.abs(pct) < 0.1) return null;                       // noise, not a reaction
  return `${sanitize(label)} ${pct > 0 ? '+' : ''}${pct.toFixed(1)}%`;
}

// ── keeping the facts the event already holds ────────────────────────────────
// "BREAKING: Saudi Arabia shuts East-West pipeline after drone damage" threw away the only number
// that explains why a trader should care: the engine's own summary says the line "can carry up to 7
// million barrels of oil a day". The headline is the event; the summary frequently holds the
// magnitude, the capacity, the location or the counterparty that makes it matter.
//
// NOTHING IS WRITTEN HERE. One clause is lifted VERBATIM from the event's own summary and appended.
// It is chosen only if it carries a figure the post does not already state, so the post can gain a
// fact but never a characterisation, and the words are the source's own rather than a paraphrase
// this module invented.
const CLAUSE_SPLIT = /(?:[.;]|,\s+(?:which|who|where|after|while|as)\b)/i;
const FIGURE = /\b\d+(?:[.,]\d+)?\s*(?:%|percent|million|billion|trillion|bn|mn|barrels?|bpd|b\/d|tonnes?|tons?|gw|mw|km|miles?|people|jobs?|basis points|bps)\b|\$\s?\d/i;
// A clause that is opinion, attribution or boilerplate adds no fact and often adds a publisher.
const CLAUSE_NOISE = /\b(?:said|says|according to|reported|sources?|analysts?|we |our |company said|spokesperson|statement|believe|expects?)\b/i;
export const MAX_APPEND = 90;

// Words a fact clause can begin on. Used to find the smallest verbatim window around a figure when
// the whole clause is too long to append.
// Deliberately NO bare participles. "Houthis seize Red Sea islands in offensive; carrying 12
// million barrels a day" attaches the clause to the islands, which is not what the source said —
// the artery carries the barrels. A window may only start where the text can stand on its own, so
// appending it cannot change what the sentence claims.
// Only UNAMBIGUOUS quantifier phrases. "over", "about", "around" and "nearly" double as
// prepositions and adverbs, and starting a window on one produced "Houthis seize Red Sea islands in
// offensive; over a shipping artery carrying 12 million barrels a day" — a fragment that reads as
// nonsense. When no clean window exists the post simply keeps the headline, and the vagueness rule
// then decides whether that is enough to publish at all.
const WINDOW_START = /\b(?:worth|valued at|up to|more than|at least|roughly|approximately|equal to|equivalent to)\b/gi;

// A clause has to be able to stand on its own. One opening on a participle or a preposition
// re-attaches to whatever noun ended the headline: "Houthis seize Red Sea islands in offensive;
// carrying 12 million barrels a day" says the islands carry the barrels, which the source did not.
const WEAK_OPENER = /^(?:carrying|affecting|covering|supplying|producing|handling|holding|accounting|representing|totall?ing|including|involving|adding|reaching|making|leaving|giving|bringing|over|under|about|around|near|between|among|with|without|for|to|of|in|on|at|by|from|and|or|but)\b/i;

function usable(piece, head) {
  if (!piece || piece.length > MAX_APPEND || piece.length < 12) return null;
  if (WEAK_OPENER.test(piece)) return null;
  if (!FIGURE.test(piece)) return null;                      // only a clause that carries a figure
  if (CLAUSE_NOISE.test(piece)) return null;
  // Already said? Compare the figures, not the words.
  const nums = (piece.match(/\d+(?:[.,]\d+)?/g) || []).map((n) => n.replace(/,/g, ''));
  if (nums.length && nums.every((n) => head.includes(n))) return null;
  return piece.charAt(0).toLowerCase() + piece.slice(1);
}

export function supportingClause(headline, summary) {
  const head = String(headline || '').toLowerCase();
  const body = String(summary || '').replace(/\s+/g, ' ').trim();
  if (!body) return null;
  for (let piece of body.split(CLAUSE_SPLIT)) {
    piece = piece.replace(/^\s*(?:which|who|that|and|but)\s+/i, '').replace(/[\s,;:]+$/, '').trim();
    const hit = usable(piece, head);
    if (hit) return hit;
    // The clause carries a figure but is too long to append whole. Take the smallest VERBATIM
    // window that still contains it, starting at a natural clause opener.
    if (!piece || !FIGURE.test(piece) || CLAUSE_NOISE.test(piece)) continue;
    WINDOW_START.lastIndex = 0;
    const starts = [...piece.matchAll(WINDOW_START)].map((m) => m.index);
    const fig = piece.search(FIGURE);
    for (const st of starts.filter((i) => i <= fig).reverse()) {
      const win = usable(piece.slice(st).replace(/^\s*(?:which|that)\s+/i, '').trim(), head);
      if (win) return win;
    }
  }
  return null;
}

// ── is this worth a trader's attention as written ────────────────────────────
// "Houthis seize Red Sea islands in offensive" names no island, no number and no consequence. After
// the enrichment above has had its chance, a post still carrying no figure and no concrete object
// is a headline pretending to be news.
const CONCRETE = /\b\d|\$|%|\b(?:fda|sec|doj|ftc|opec|fed|ecb|boj|approval|approves?|acquisition|acquires?|merger|tender offer|delisting|bankruptcy|default|halted|suspension|recall|indict\w*|sanctions?)\b/i;

/**
 * Is this post a worse version of the event it came from?
 *
 * The test is NOT "is it short". "Saudi Arabia shuts East-West pipeline after drone attacks" is
 * eight words with no figure and is a perfectly good post — it names who, what and where, and if
 * the event holds nothing more then that IS the news. What makes a post bad is being LESS
 * informative than the event behind it: the engine holds a figure that explains why it matters, the
 * post does not carry it, and the append step could not attach it safely. Publishing then means
 * choosing the weaker sentence when a stronger one was available.
 *
 * So the rule is: featureless AND the event demonstrably held more. Everything else publishes.
 */
export function tooVagueToPost(text, { hasTicker = false, isHalt = false, unusedContext = false } = {}) {
  // A post about a NAMED SECURITY is never featureless: the symbol is the fact. Same for a halt,
  // where the event IS that trading stopped.
  if (hasTicker || isHalt) return false;
  const s = String(text || '').replace(/^(?:BREAKING:\s*)?(?:\$[A-Z]{1,5}:?\s*)?/i, '').trim();
  if (CONCRETE.test(s)) return false;                        // carries a figure or a named authority
  return unusedContext && s.split(/\s+/).filter(Boolean).length <= 12;
}

// ── cashtags ─────────────────────────────────────────────────────────────────
// The symbols on a post come from the canonical event's OWN resolved tickers — the same field Pit
// Wire renders — and this file never maps a company name to a symbol itself. A hardcoded mapping
// here would be a second, quietly diverging source of truth; resolving upstream is what keeps the
// two surfaces from disagreeing.
//
// Three refusals:
//   • a taxonomy label (MACRO, FED, HALT) is a desk category, not a security
//   • anything not shaped like a listed symbol, so a stray phrase never becomes a cashtag
//   • duplicates, including one symbol contributed by two sources in the cluster
// Share classes survive exactly as resolved: BRK.B stays BRK.B and GOOG is never widened to GOOGL.
// A name that was ambiguous resolved to nothing upstream and arrives here as no ticker at all,
// which is the intended outcome — no ticker is better than a wrong ticker.
const TICKER_SHAPE = /^[A-Z]{1,6}(?:[.\-][A-Z]{1,2})?$/;
export const MAX_CASHTAGS = 3;
export const escapeRe = (s) => String(s).replace(/[.*+?^${}()|[\]\\]/g, (m) => `\\${m}`);

export function cashtags(ev) {
  const out = [];
  for (const raw of (ev?.tickers || [])) {
    const t = String(raw || '').trim().toUpperCase();
    if (!t || isTaxonomyLabel(t) || !TICKER_SHAPE.test(t)) continue;
    if (!out.includes(t)) out.push(t);
    if (out.length >= MAX_CASHTAGS) break;
  }
  return out;
}

// ── formatting ───────────────────────────────────────────────────────────────
// Three shapes, exactly as specified:
//   macro / geopolitical        BREAKING: <event>
//   ticker-specific             $TICKER: <event>
//   exceptional ticker event    BREAKING: $TICKER <event>   (exceptional = CRITICAL)
export function formatPost(ev, reading = null, now = Date.now(), breaking = null) {
  // Every public company the canonical event resolved, not just the first. A two-company event —
  // an acquisition, a supply deal, a licensing agreement — is about both of them, and tagging only
  // the acquirer leaves the other side silently untagged.
  const tags = cashtags(ev);
  const ticker = tags[0] || null;
  let body = sanitize(ev?.headline);
  if (!body) return { ok: false, error: 'no headline' };

  // canonicalHeadline prefixes a resolved symbol ("MSFT: Microsoft sets limits…"). Left in it would
  // read "$MSFT: MSFT: Microsoft…".
  //
  // A SEPARATOR IS REQUIRED. Without one this also ate the sentence's SUBJECT whenever a company's
  // name happens to be its symbol: "Trex lifts outlook citing demand" became "$TREX: lifts outlook
  // citing demand", a sentence with nothing doing the lifting. The engine's own prefix always
  // carries a colon or a dash, so demanding one removes exactly what was added and never a word the
  // source wrote. Escaped, because a share class carries a dot (BRK.B) and an unescaped dot is a
  // regex wildcard that would eat a real character.
  for (const t of tags) body = body.replace(new RegExp(`^\\$?${escapeRe(t)}\\s*[:\\-]\\s+`, 'i'), '');
  // Exchange halt lines are assembled by the engine from feed fields and still carry its separator
  // and the exchange's own reason code. "$AAPL: AAPL halted, volatility pause (LULD)" is the symbol
  // twice and a code no reader needs.
  if (String(ev?.source_type || '') === 'halt') {
    // The feed's reason field is not prose. "DFTX halted, News & resumption times" and "VRC halted,
    // Halt (M)" are column contents and an exchange code. The reason is normalised to the three
    // things a reader needs, and anything unrecognised is simply dropped.
    const reason = /\bnews\b/i.test(body) ? 'news pending'
      : /\b(?:regulatory|suspension)\b/i.test(body) ? 'regulatory halt'
        : /\b(?:volatility|luld)\b/i.test(body) ? 'volatility pause'
          : null;
    body = reason ? `halted, ${reason}` : 'halted';
  }
  body = body.replace(/^breaking\s*[:\-]\s*/i, '').trim();
  if (!body) return { ok: false, error: 'nothing left after sanitising' };

  // BREAKING is decided by the publication gate, not by the impact score. Passing null keeps the
  // old score-based behaviour for direct callers and tests that predate the gate.
  const brk = breaking === null ? Number(ev?.importance) === CRITICAL : !!breaking;
  // FOUR shapes, not three. A measured macro print that is real and useful but not urgent —
  // "Canada inflation holds at 3.0% year-over-year in August" — goes out as a plain trader-wire
  // line. Without this shape every no-ticker post had to be labelled BREAKING, which is how the
  // label ended up on 68 of 68 candidates and stopped meaning anything.
  const tagStr = tags.map((t) => `$${t}`).join(' ');
  const prefix = tagStr ? (brk ? `BREAKING: ${tagStr} ` : `${tagStr}: `) : (brk ? 'BREAKING: ' : '');

  // Add back a fact the event holds and the headline dropped, in the source's own words.
  const extra = supportingClause(body, ev?.summary);
  if (extra) {
    const merged = `${body.replace(/[.\s]+$/, '')}; ${extra}`;
    if (merged.length <= MAX_POST - 24) body = merged;
  }

  const reaction = reactionLine(reading, now);
  const tail = reaction ? `\n${reaction}` : '';
  const text = prefix + clamp(body, MAX_POST - prefix.length - tail.length) + tail;
  // The event held a figure the post could not carry: publishing would be the weaker sentence.
  const unusedContext = !extra && FIGURE.test(String(ev?.summary || ''));
  if (tooVagueToPost(text, { hasTicker: !!ticker, isHalt: String(ev?.source_type || '') === 'halt', unusedContext })) {
    return { ok: false, error: 'less informative than the event it came from' };
  }

  if (FORBIDDEN.test(text)) return { ok: false, error: 'forbidden character survived sanitising' };
  if (text.length > MAX_POST) return { ok: false, error: `too long (${text.length})` };
  if (/#[A-Za-z0-9_]/.test(text)) return { ok: false, error: 'hashtag survived sanitising' };
  if (URL.test(text)) return { ok: false, error: 'url survived sanitising' };
  const shape = ticker ? (brk ? 'breaking_ticker' : 'ticker') : (brk ? 'breaking' : 'plain');
  return { ok: true, text, chars: text.length, shape };
}

// The whole decision in one call: eligible, then PUBLISHABLE, then formatted.
//
// Eligibility and publication are separate on purpose. Eligibility answers "may Catalyst Pit post
// this", publication answers "should it", and only the second one knows what the account is for.
// A `suppressed` result is terminal and carries an auditable reason; a `blocked` result beginning
// "awaiting" is transient and the event is reconsidered on the next pass.
export function buildCandidate(ev, reading = null, now = Date.now(), priorPosts = null) {
  const verdict = evaluate(ev);
  if (!verdict.eligible) return { eligible: false, reason: null, blocked: verdict.blocked };

  // The story guard runs FIRST now. It still decides publication below, but whether the account has
  // already told this story is also an INPUT to the BREAKING decision: a second post on a
  // developing story is a follow-up, and a follow-up is not breaking news.
  const story = priorPosts ? storyVerdict({ headline: ev.headline, text: '' }, priorPosts, now)
    : { post: true, reason: null, storyKey: null, priors: 0 };

  const quality = publicationVerdict({ ...ev, storyHasPriors: (story.priors || 0) > 0 }, now);
  if (!quality.publish) {
    return { eligible: true, publishable: false, reason: verdict.reason,
      suppressed: quality.reason, terminal: quality.terminal };
  }

  const post = formatPost(ev, reading, now, quality.breaking);
  if (!post.ok) return { eligible: true, publishable: false, reason: verdict.reason,
    suppressed: post.error, terminal: true };

  // The story verdict computed above decides it. X-only — Pit Wire's canonical dedupe is not
  // consulted and not affected.
  if (!story.post) {
    return { eligible: true, publishable: false, reason: verdict.reason,
      suppressed: story.reason, terminal: true, storyKey: story.storyKey };
  }

  return { eligible: true, publishable: true, reason: verdict.reason, breaking: quality.breaking,
    storyKey: story.storyKey, facts: [...factsOf(ev.headline)].join(','), ...post };
}
