// ORDINARY ENGLISH WORDS, MEASURED FROM OUR OWN HEADLINES.
//
//   node scripts/build-common-words.mjs        # rewrites src/lib/common-words.mjs
//
// ⚠️ WHY THIS EXISTS, AND WHY IT IS NOT A BLOCKLIST.
//
// A company whose whole registered name reduces to ONE token is indistinguishable, at match time,
// from that word being used as a word. "Here Group Ltd" reduces to HERE; a headline reading
// "…Buying Bitcoin Again. Here's Why…" therefore resolved to $HERE, on a story about Michael Saylor.
// The same shape produced $BYON from "Beyond", $NWGL from "Workshop" and $MSTR from "Strategy".
//
// Until now the only defence was AMBIGUOUS_WORD in company-symbols.mjs — a hand-written list of
// words someone had already been burned by. That is not an architecture: it cannot know about the
// word that burns you tomorrow, and every incident grows it by one line.
//
// THE PROPERTY WE ACTUALLY WANT is "this is an ordinary English word", and our own corpus answers it
// directly and without a dictionary: an ordinary word is written LOWERCASE in headlines constantly,
// and a company name essentially never is. Measured over 65,825 Pit Wire headlines:
//
//     here 7    on 5402   for 8215   now 131   open 133   love 4    can 138   beyond 57
//     strategy 150        workshop 4           answer 6
//     nvidia 0  tesla 0   costco 0   palantir 0          microsoft 0         amazon 0
//     netflix 0 pfizer 0  kyndryl 0  apple 1   moderna 1
//
// The separation is not marginal — it is the difference between a word and a name. THREE lowercase
// uses is the floor, which keeps Apple and Moderna (1 each) resolving by name while refusing Here,
// Love, Workshop and Answer (4 or more each).
//
// A company that styles its OWN name in lowercase — argenx — is the one case this misreads, and it
// is answered the way every deliberate fact in this file is answered: a curated alias.
//
// Regenerate whenever the corpus has grown meaningfully. The output is committed so the resolver
// stays pure, synchronous and testable without a database.
import fs from 'node:fs';
import path from 'node:path';
import { neon } from '@neondatabase/serverless';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'src', 'lib', 'common-words.mjs');
const MIN_LOWERCASE_USES = 3;

const env = fs.readFileSync(path.join(ROOT, '.env.local'), 'utf8');
const url = /DATABASE_URL\s*=\s*"?([^"\n\r]+)"?/.exec(env)?.[1];
if (!url) throw new Error('DATABASE_URL not found in .env.local');
const sql = neon(url.trim());

const rows = await sql`SELECT headline FROM primary_events WHERE headline IS NOT NULL`;
console.log(`headlines scanned: ${rows.length}`);

// A token is counted as ORDINARY only when it was written entirely in lower case. Capitalised uses
// are ignored on purpose: headlines are frequently Title Case, where capitalisation proves nothing.
const lower = new Map();
for (const r of rows) {
  for (const m of String(r.headline).matchAll(/[A-Za-z][A-Za-z'’\-]*/g)) {
    const w = m[0];
    if (w !== w.toLowerCase()) continue;
    const k = w.toUpperCase().replace(/['’\-]/g, '');
    if (k.length < 2 || !/^[A-Z]+$/.test(k)) continue;
    lower.set(k, (lower.get(k) || 0) + 1);
  }
}

const words = [...lower].filter(([, n]) => n >= MIN_LOWERCASE_USES).map(([w]) => w).sort();
console.log(`distinct lowercase tokens: ${lower.size}`);
console.log(`kept at >= ${MIN_LOWERCASE_USES} uses: ${words.length}`);

const body = `// GENERATED by scripts/build-common-words.mjs — do not edit by hand.
//
// Words written in lower case in Catalyst Pit's own headlines, which is the evidence that they are
// ORDINARY ENGLISH WORDS rather than names. A company whose whole registered name reduces to one of
// these is not indexable by name: "Here Group Ltd" reduces to HERE, and a headline saying "Here's
// why" would otherwise resolve to $HERE. See the generator for the measurement and the reasoning.
//
// Corpus: ${rows.length} headlines. Floor: ${MIN_LOWERCASE_USES} lowercase uses. Words: ${words.length}.
// Regenerated: ${new Date().toISOString().slice(0, 10)}
export const COMMON_WORDS = new Set([
${words.map((w) => `  '${w}',`).join('\n')}
]);

/** Is this token an ordinary English word rather than a name? */
export const isCommonWord = (tok) => COMMON_WORDS.has(String(tok || '').toUpperCase());
`;

fs.writeFileSync(OUT, body, 'utf8');
console.log(`wrote ${OUT}`);
